CREATE TABLE IF NOT EXISTS bar_cash_movement (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    cash_shift_id UUID NOT NULL REFERENCES cash_shift(id) ON DELETE CASCADE,
    type VARCHAR(3) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    created_by UUID REFERENCES app_user(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS bar_day_close (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    business_date DATE NOT NULL UNIQUE,
    status VARCHAR(10) NOT NULL DEFAULT 'CLOSED',
    closed_by UUID REFERENCES app_user(id) ON DELETE SET NULL,
    closed_at TIMESTAMPTZ,
    reopened_by UUID REFERENCES app_user(id) ON DELETE SET NULL,
    reopened_at TIMESTAMPTZ,
    reopen_reason VARCHAR(255),
    snapshot JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS bar_payment (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    bar_order_id UUID NOT NULL REFERENCES bar_order(id) ON DELETE CASCADE,
    method VARCHAR(10) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    tendered NUMERIC(12,2) NOT NULL,
    change_given NUMERIC(12,2) NOT NULL DEFAULT 0,
    reference VARCHAR(255),
    received_by UUID REFERENCES app_user(id) ON DELETE SET NULL,
    cash_shift_id UUID REFERENCES cash_shift(id) ON DELETE SET NULL,
    ledger_payment_id UUID,
    idempotency_key VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);
