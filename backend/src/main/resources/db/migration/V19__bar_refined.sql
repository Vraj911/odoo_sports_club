CREATE SEQUENCE IF NOT EXISTS bar_order_no_seq START WITH 1000;

CREATE TABLE IF NOT EXISTS bar_tab (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    member_id UUID REFERENCES member(id) ON DELETE SET NULL,
    guest_name VARCHAR(255),
    table_id UUID REFERENCES bar_table(id) ON DELETE SET NULL,
    opened_by UUID REFERENCES app_user(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    limit_amount NUMERIC(12,2),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    approved_by UUID REFERENCES app_user(id) ON DELETE SET NULL,
    move_reason VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

